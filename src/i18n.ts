// UI strings: English source text is the key, `pl` holds the Polish translation. Shared by the renderer and electron/.
export type Lang = "en" | "pl";

/** Selectable interface languages, shown by their native names. */
export const languages: [Lang, string][] = [
  ["en", "English"],
  ["pl", "Polski"],
];

let lang: Lang = "en";
export const setLang = (l: Lang) => {
  lang = l;
};

const fill = (s: string, vars?: Record<string, string | number>) =>
  vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;

export function t(text: string, vars?: Record<string, string | number>): string {
  return fill((lang === "pl" && pl[text]) || text, vars);
}

/** plural(n, "{n} project", "{n} projects"); Polish forms live in `pl` under "one|other" as "one|few|many". */
export function plural(n: number, one: string, other: string): string {
  let s = n === 1 ? one : other;
  const forms = lang === "pl" && pl[`${one}|${other}`];
  if (forms) {
    const [a, b, c] = forms.split("|");
    const d = n % 10, dd = n % 100;
    s = n === 1 ? a : d >= 2 && d <= 4 && (dd < 12 || dd > 14) ? b : c;
  }
  return fill(s, { n });
}

