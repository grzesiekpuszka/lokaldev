import fs from "node:fs";
import path from "node:path";
import { proxied, type Project } from "../src/api";
import { port } from "./config";
import { certFor } from "./ssl";
import { binDir } from "./versions";
import { fwd, p, runElevated } from "./util";
import { t } from "../src/i18n";

export const WORKERS = 4;
export const phpPort = (ver: string) => 9000 + Number(ver.replace(".", "")) * 10;
const id = (ver: string) => ver.replace(".", "");

const MODULES = [
  "access_compat", "alias", "auth_basic", "authn_core", "authn_file", "authz_core", "authz_host", "authz_user",
  "autoindex", "deflate", "dir", "env", "expires", "filter", "headers", "lbmethod_byrequests", "log_config", "mime",
  "negotiation", "proxy", "proxy_balancer", "proxy_fcgi", "proxy_http", "rewrite", "setenvif", "slotmem_shm",
  "socache_shmcb", "ssl",
];

const docroot = (x: Project) => fwd(path.join(x.path, proxied(x.type) ? "" : x.docroot));

export const sitesDir = (server: string) => p("etc", server, "sites-enabled");
const autoName = (domain: string) => (domain === "localhost" ? "00-default.conf" : `auto.${domain}.conf`);
export const customFile = (server: string, domain: string) => path.join(sitesDir(server), `${domain}.conf`);
export const autoFile = (server: string, domain: string) => path.join(sitesDir(server), autoName(domain));

/**
 * Writes one generated file per site (auto.<domain>.conf, 00-default.conf for localhost), like Laragon.
 * A hand-written <domain>.conf in the same folder wins: its auto file is not generated. Custom files are never touched.
 */
function writeSites(server: string, sites: [Project, string][]) {
  const dir = sitesDir(server);
  fs.mkdirSync(dir, { recursive: true });
  const keep = new Set<string>();
  for (const [x, content] of sites) {
    if (fs.existsSync(customFile(server, x.domain))) continue;
    keep.add(autoName(x.domain));
    fs.writeFileSync(autoFile(server, x.domain), content);
  }
  for (const f of fs.readdirSync(dir)) {
    if ((f.startsWith("auto.") || f === "00-default.conf") && !keep.has(f)) fs.rmSync(path.join(dir, f));
  }
}

/** Names and mtimes of hand-written site files; part of the "config is stale" check. */
export function customStamp(server: string) {
  try {
    return fs
      .readdirSync(sitesDir(server))
      .filter((f) => !f.startsWith("auto.") && f !== "00-default.conf")
      .map((f) => `${f}:${fs.statSync(path.join(sitesDir(server), f)).mtimeMs}`)
      .join("|");
  } catch {
    return "";
  }
}

function write(name: string, s: string) {
  const file = p("etc", name);
  fs.writeFileSync(file, s);
  return file;
}

export function apache(projects: Project[], versions: string[]) {
  const data = fwd(p());
  const ssl = projects.some((x) => x.ssl);
  let s = `ServerRoot "${fwd(binDir("apache"))}"
Listen 127.0.0.1:${port("apache_http")}
${ssl ? `Listen 127.0.0.1:${port("apache_https")}\nSSLSessionCache "shmcb:${data}/tmp/ssl_scache(512000)"\n` : ""}ServerName localhost
${MODULES.map((m) => `LoadModule ${m}_module modules/mod_${m}.so`).join("\n")}
AcceptFilter http none
AcceptFilter https none
EnableSendfile off
PidFile "${data}/tmp/httpd.pid"
ErrorLog "${data}/logs/apache_error.log"
LogLevel warn
TypesConfig conf/mime.types
DirectoryIndex index.php index.html
Timeout 300
ProxyTimeout 300
<Directory />
    AllowOverride None
    Require all denied
</Directory>
`;
  for (const v of versions) {
    s += `<Proxy "balancer://php${id(v)}">\n`;
    for (let i = 0; i < WORKERS; i++) s += `    BalancerMember "fcgi://127.0.0.1:${phpPort(v) + i}"\n`;
    s += "</Proxy>\n";
  }
  s += `IncludeOptional "${fwd(sitesDir("apache"))}/*.conf"\n`;

  writeSites(
    "apache",
    projects.map((x) => {
      const root = docroot(x);
      // Windows paths lack a leading slash, hence the trailing "/" on the balancer and the explicit SCRIPT_FILENAME.
      const handler =
        proxied(x.type)
          ? `    ProxyPreserveHost On
    ProxyPass / "http://127.0.0.1:${x.node_port}/" upgrade=websocket
    ProxyPassReverse / "http://127.0.0.1:${x.node_port}/"
`
          : x.php
            ? `    ProxyFCGIBackendType GENERIC
    ProxyFCGISetEnvIf "true" SCRIPT_FILENAME "%{DOCUMENT_ROOT}%{reqenv:SCRIPT_NAME}"
    <FilesMatch "\.php$">
        SetHandler "proxy:balancer://php${id(x.php)}/"
    </FilesMatch>
`
            : "";
      const body = `    ServerName ${x.domain}
${x.domain === "localhost" ? "" : `    ServerAlias *.${x.domain}\n`}    DocumentRoot "${root}"
    <Directory "${root}">
        Options Indexes FollowSymLinks
        AllowOverride All
        Require all granted
    </Directory>
${handler}`;
      let site = `# Generated by lokaldev. To customize, save a copy as ${x.domain}.conf in this folder; this file is then no longer created.\n`;
      site += `<VirtualHost *:${port("apache_http")}>\n${body}</VirtualHost>\n`;
      if (x.ssl) {
        const c = certFor(x.domain);
        site += `<VirtualHost *:${port("apache_https")}>\n${body}    SSLEngine on\n    SSLCertificateFile "${fwd(c.cert)}"\n    SSLCertificateKeyFile "${fwd(c.key)}"\n</VirtualHost>\n`;
      }
      return [x, site];
    }),
  );
  return write("httpd.conf", s);
}

export function nginx(projects: Project[], versions: string[]) {
  const data = fwd(p());
  let s = `worker_processes 1;
error_log "${data}/logs/nginx_error.log";
pid "${data}/tmp/nginx.pid";
events { worker_connections 1024; }
http {
    include "${fwd(binDir("nginx"))}/conf/mime.types";
    default_type application/octet-stream;
    sendfile off;
    access_log off;
    client_max_body_size 256m;
    server_names_hash_bucket_size 128;
    map $http_upgrade $connection_upgrade { default upgrade; '' close; }
`;
  for (const v of versions) {
    s += `    upstream php${id(v)} {\n`;
    for (let i = 0; i < WORKERS; i++) s += `        server 127.0.0.1:${phpPort(v) + i};\n`;
    s += "    }\n";
  }
  s += `    include "${fwd(sitesDir("nginx"))}/*.conf";\n}\n`;

  writeSites(
    "nginx",
    projects.map((x) => {
      const def = x.domain === "localhost" ? " default_server" : "";
      let site = `# Generated by lokaldev. To customize, save a copy as ${x.domain}.conf in this folder; this file is then no longer created.
server {
    listen 127.0.0.1:${port("nginx_http")}${def};
    server_name ${x.domain === "localhost" ? "localhost 127.0.0.1" : `${x.domain} *.${x.domain}`};
    root "${docroot(x)}";
    index index.php index.html;
    autoindex on;
    charset utf-8;
`;
      if (x.ssl) {
        const c = certFor(x.domain);
        site += `    listen 127.0.0.1:${port("nginx_https")} ssl${def};\n    ssl_certificate "${fwd(c.cert)}";\n    ssl_certificate_key "${fwd(c.key)}";\n`;
      }
      if (proxied(x.type)) {
        site += `    location / {
        proxy_pass http://127.0.0.1:${x.node_port};
        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection $connection_upgrade;
        proxy_set_header Host $host;
        proxy_set_header X-Forwarded-Proto $scheme;
    }
`;
      } else if (x.php) {
        site += `    location / { try_files $uri $uri/ /index.php?$query_string; }
    location ~ \.php$ {
        include "${fwd(binDir("nginx"))}/conf/fastcgi_params";
        fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;
        fastcgi_param HTTPS $https if_not_empty;
        fastcgi_pass php${id(x.php)};
        fastcgi_read_timeout 300;
    }
`;
      } else {
        site += "    location / { try_files $uri $uri/ =404; }\n";
      }
      return [x, `${site}}\n`];
    }),
  );
  return write("nginx.conf", s);
}

const HOSTS = "C:\\Windows\\System32\\drivers\\etc\\hosts";
const START = "# lokaldev start";
const END = "# lokaldev end";
// blocks written under earlier names are replaced too
const isStart = (l: string) => l === START || l === "# lokal.dev start" || l === "# Lokal start" || l === "# LaraGone start";
const isEnd = (l: string) => l === END || l === "# lokal.dev end" || l === "# Lokal end" || l === "# LaraGone end";

/** Rewrites the lokaldev block in the hosts file; asks for elevation only when it changes. */
export async function updateHosts(domains: string[]) {
  const cur = fs.readFileSync(HOSTS, "utf8");
  let skip = false;
  let out = "";
  for (const line of cur.split(/\r?\n/)) {
    if (isStart(line)) skip = true;
    else if (isEnd(line)) skip = false;
    else if (!skip) out += `${line}\r\n`;
  }
  out = out.replace(/(\r\n)+$/, "\r\n");
  if (domains.length) out += `${START}\r\n${domains.map((d) => `127.0.0.1 ${d}\r\n`).join("")}${END}\r\n`;
  if (out === cur) return;

  const tmp = p("tmp", "hosts");
  fs.writeFileSync(tmp, out);
  await runElevated("cmd.exe", `/c copy /y "${tmp}" "${HOSTS}"`);
  if (fs.readFileSync(HOSTS, "utf8") !== out) throw new Error(t("The hosts file wasn't updated (UAC cancelled?)"));
}

